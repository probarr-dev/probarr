"""The list of channels you actually want.

This is the single most important input for a large provider. Without it,
verification means probing every candidate for all 55,000 listed streams,
which is not a long job -- it is an impossible one. With it, probarr probes
only candidates for the couple of hundred channels you care about.

Format is deliberately the plainest thing that works, so it can be written by
hand, generated by a script, or pasted from a channel-lineup web page:

    # comments and blank lines ignored
    101: BBC One
    102: BBC Two
    BBC Four            <- number optional
    401: Meridian Sports Main Event | meridian.main.uk    <- optional tvg-id after |

    [Meridian Sports]                                  <- optional group header
    407: Meridian Sports 1
    408: Meridian Sports Golf

Numbering is preserved so an exported playlist can carry real channel numbers
rather than the order things happened to be probed in.

A `[Group Name]` line on its own sets the group for every channel line that
follows, until the next header (or end of file). This exists so Curate's
Groups view doesn't have to be rebuilt by hand on every new run of the same
lineup: a channel's group is a durable per-channel decision already carried
forward for an *existing* lineup (see lineups.py), but that inheritance has
nothing to inherit FROM on a lineup's very first run -- a header in the
wantlist itself seeds it from the start. It only ever seeds; a group set
afterwards in Curate always wins over what the wantlist says on the next run.
An empty `[]` resets to no group, for channels between two named sections
that don't belong in either.
"""
